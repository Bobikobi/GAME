/**
 * The creators board (spec C-1): creator points and hours of work, computed
 * from the repository history and the content that is in the game now.
 *
 *   points = 10 for every content record the creator has in the game
 *          + 1 for every commit that changed their files
 *   hours  = commit sessions: commits less than two hours apart are one
 *            session, and every session also counts half an hour of the work
 *            before its first commit. A guess, said as one in the game.
 *
 * Core is the main developer: every commit in the repository counts for it.
 * A creator's commits are those that touched content/extensions/<handle>/ or
 * content/kit/<handle>/. Points for reviewers come with the server.
 *
 * `pnpm board` writes content/board.json, which is committed: a deploy builds
 * from a shallow clone that cannot see the history.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import type { BoardEntry, Credit } from '@game/kernel';
import { BOARD_PATH, REPO_ROOT } from './load';

export const BOARD_FILE = BOARD_PATH;
export const POINTS_PER_RECORD = 10;
export const POINTS_PER_COMMIT = 1;
/** Commits closer than this are one working session. */
export const SESSION_GAP_S = 2 * 3600;
/** Work before the first commit of a session. */
export const SESSION_LEAD_S = 30 * 60;

export interface Commit {
  /** unix seconds */
  at: number;
  files: string[];
}

/** Hours of work from commit times, rounded to the half hour. */
export function sessionHours(times: readonly number[]): number {
  const sorted = [...times].sort((a, b) => a - b);
  let seconds = 0;
  let start = sorted[0];
  let last = sorted[0];
  for (const t of sorted.slice(1)) {
    if (t - last! >= SESSION_GAP_S) {
      seconds += last! - start! + SESSION_LEAD_S;
      start = t;
    }
    last = t;
  }
  if (start !== undefined && last !== undefined) seconds += last - start + SESSION_LEAD_S;
  return Math.round(seconds / 1800) / 2;
}

/** Which creators a commit worked for: core always, others by the files it touched. */
export function creatorsOf(commit: Commit): Set<string> {
  const out = new Set<string>(['core']);
  for (const f of commit.files) {
    const m = /^content\/(?:extensions|kit)\/([a-z0-9_-]+)\//.exec(f);
    if (m && m[1] !== 'core') out.add(m[1]!);
  }
  return out;
}

export function computeBoard(commits: readonly Commit[], credits: readonly Credit[]): Record<string, BoardEntry> {
  const times = new Map<string, number[]>();
  for (const c of commits) for (const who of creatorsOf(c)) (times.get(who) ?? times.set(who, []).get(who)!).push(c.at);
  const records = new Map<string, number>();
  for (const c of credits) records.set(c.creator, (records.get(c.creator) ?? 0) + 1);
  const handles = [...new Set([...times.keys(), ...records.keys()])].sort();
  const board: Record<string, BoardEntry> = {};
  for (const handle of handles) {
    const t = times.get(handle) ?? [];
    const n = records.get(handle) ?? 0;
    board[handle] = { points: POINTS_PER_RECORD * n + POINTS_PER_COMMIT * t.length, records: n, hours: sessionHours(t) };
  }
  return board;
}

/** Every commit with its time and files, oldest first. Commits that only rewrote the board do not count. */
export function readCommits(cwd = REPO_ROOT): Commit[] {
  const out = execFileSync('git', ['log', '--reverse', '--name-only', '--format=%x00%ct'], { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const commits: Commit[] = [];
  for (const block of out.split('\0').slice(1)) {
    const [head, ...files] = block.split('\n').filter((l) => l.trim() !== '');
    const at = Number(head);
    if (!Number.isFinite(at)) continue;
    if (files.length > 0 && files.every((f) => f === 'content/board.json')) continue;
    commits.push({ at, files });
  }
  return commits;
}

export function readBoard(): Record<string, BoardEntry> {
  if (!existsSync(BOARD_FILE)) return {};
  try {
    const data = JSON.parse(readFileSync(BOARD_FILE, 'utf8')) as { board?: Record<string, BoardEntry> };
    return data.board ?? {};
  } catch {
    return {};
  }
}

export function writeBoard(board: Record<string, BoardEntry>): void {
  const note = 'Creators board (spec C-1), generated by "pnpm board" from the git history. Do not edit by hand.';
  writeFileSync(BOARD_FILE, `${JSON.stringify({ format: 1, note, board }, null, 2)}\n`);
}
